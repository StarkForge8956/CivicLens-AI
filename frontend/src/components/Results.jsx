import { useState } from "react"
import {
  createIncidentReport,
  getIncidentReport,
  submitIncidentReport,
} from "../services/api"

const API_ORIGIN = "http://127.0.0.1:8000"

function Results({ result }) {
  const detections = result?.detections || []

  const annotatedImageUrl = result?.annotated_url
    ? `${API_ORIGIN}${result.annotated_url}`
    : null

  const [creatingReport, setCreatingReport] = useState(false)
  const [submittingReport, setSubmittingReport] = useState(false)
  const [report, setReport] = useState(null)
  const [reportMessage, setReportMessage] = useState("")
  const [reportError, setReportError] = useState("")

  const handleCreateReport = async (detectionId) => {
    try {
      setCreatingReport(true)
      setReportMessage("")
      setReportError("")

      const created = await createIncidentReport(detectionId)

      const reportData = await getIncidentReport(
        created.report_id
      )

      setReport(reportData)

      setReportMessage(
        `${created.report_number} created successfully.`
      )
    } catch (error) {
      setReportError(
        error.message || "Failed to create civic report."
      )
    } finally {
      setCreatingReport(false)
    }
  }

  const handleSubmitReport = async () => {
    if (!report?.report?.id) return

    try {
      setSubmittingReport(true)
      setReportError("")
      setReportMessage("")

      const submitted = await submitIncidentReport(
        report.report.id
      )

      setReport({
        ...report,
        report: {
          ...report.report,
          status: submitted.status,
          authority_name: submitted.authority_name,
          authority_reference:
            submitted.authority_reference,
          submitted_at: submitted.submitted_at,
        },
      })

      setReportMessage(
        `${submitted.report_number} submitted successfully.`
      )
    } catch (error) {
      setReportError(
        error.message || "Failed to submit civic report."
      )
    } finally {
      setSubmittingReport(false)
    }
  }

  return (
    <section className="results-section">
      <div className="results-header">
        <div>
          <p className="section-eyebrow">AI RESULTS</p>
          <h2>Detection Results</h2>
          <p>
            AI-identified civic infrastructure issues from your
            uploaded image.
          </p>
        </div>

        {result && (
          <div className="results-count">
            <strong>{detections.length}</strong>
            <span>
              {detections.length === 1
                ? "Issue Detected"
                : "Issues Detected"}
            </span>
          </div>
        )}
      </div>

      {!result && (
        <div className="results-empty">
          <div className="results-empty-icon">⌁</div>
          <h3>No analysis available</h3>
          <p>
            Upload an image above to run CivicLens AI detection.
          </p>
        </div>
      )}

      {result && annotatedImageUrl && (
        <div className="results-image-panel">
          <div className="results-panel-header">
            <div>
              <h3>AI Detection Preview</h3>
              <p>
                Bounding boxes generated by the CivicLens AI model.
              </p>
            </div>

            <span className="ai-badge">AI ANALYZED</span>
          </div>

          <div className="annotated-image-container">
            <img
              src={annotatedImageUrl}
              alt="AI detected civic issues"
            />
          </div>
        </div>
      )}

      {result && detections.length === 0 && (
        <div className="no-detections">
          <div className="no-detections-icon">✓</div>
          <div>
            <strong>No civic issues detected</strong>
            <p>
              CivicLens AI did not identify any supported
              infrastructure issues in this image.
            </p>
          </div>
        </div>
      )}

      {detections.length > 0 && (
        <div className="detection-results-panel">
          <div className="results-panel-header">
            <div>
              <h3>Detected Issues</h3>
              <p>
                Detailed information for each AI detection.
              </p>
            </div>
          </div>

          {reportMessage && (
            <div className="report-success-message">
              ✓ {reportMessage}
            </div>
          )}

          {reportError && (
            <div className="report-error-message">
              {reportError}
            </div>
          )}

          <div className="detection-cards">
            {detections.map((detection, index) => {
              const confidence =
                detection.confidence * 100

              const severityClass =
                detection.severity?.toLowerCase() || "low"

              return (
                <div
                  className="result-detection-card"
                  key={detection.id || index}
                >
                  <div className="result-card-top">
                    <div className="issue-info">
                      <div className="issue-number">
                        {String(index + 1).padStart(2, "0")}
                      </div>

                      <div>
                        <span className="issue-label">
                          DETECTED ISSUE
                        </span>

                        <h4>{detection.class_name}</h4>
                      </div>
                    </div>

                    <span
                      className={`severity-badge ${severityClass}`}
                    >
                      {detection.severity}
                    </span>
                  </div>

                  <div className="confidence-section">
                    <div className="confidence-header">
                      <span>AI Confidence</span>
                      <strong>
                        {confidence.toFixed(1)}%
                      </strong>
                    </div>

                    <div className="confidence-bar">
                      <div
                        className="confidence-fill"
                        style={{
                          width: `${confidence}%`,
                        }}
                      ></div>
                    </div>
                  </div>

                  {detection.bbox && (
                    <div className="bbox-info">
                      <span>BOUNDING BOX</span>

                      <strong>
                        {Math.round(detection.bbox.x1)},{" "}
                        {Math.round(detection.bbox.y1)}
                        {" → "}
                        {Math.round(detection.bbox.x2)},{" "}
                        {Math.round(detection.bbox.y2)}
                      </strong>
                    </div>
                  )}

                  <button
                    className="create-report-button"
                    onClick={() =>
                      handleCreateReport(detection.id)
                    }
                    disabled={
                      creatingReport ||
                      !detection.id
                    }
                  >
                    {creatingReport
                      ? "Creating Report..."
                      : "Create Civic Report"}
                  </button>
                </div>
              )
            })}
          </div>
        </div>
      )}

      {report && (
        <div className="incident-report-panel">
          <div className="incident-report-header">
            <div>
              <p className="section-eyebrow">
                CIVIC INCIDENT REPORT
              </p>

              <h3>
                {report.report.report_number}
              </h3>

              <p>
                AI-generated incident documentation ready
                for municipal review.
              </p>
            </div>

            <span
              className={`report-status-badge ${
                report.report.status?.toLowerCase()
              }`}
            >
              {report.report.status}
            </span>
          </div>

          <div className="incident-report-content">
            <div className="incident-report-image">
              {report.incident?.stored_filename ? (
                <img
                  src={`${API_ORIGIN}/uploads/${report.incident.stored_filename}`}
                  alt="Civic incident evidence"
                />
              ) : (
                <div className="report-no-image">
                  Evidence image unavailable
                </div>
              )}
            </div>

            <div className="incident-report-details">
              <div className="report-detail-row">
                <span>Issue Type</span>
                <strong>
                  {report.detection?.class_name}
                </strong>
              </div>

              <div className="report-detail-row">
                <span>AI Confidence</span>
                <strong>
                  {report.detection?.confidence != null
                    ? `${(
                        report.detection.confidence * 100
                      ).toFixed(1)}%`
                    : "—"}
                </strong>
              </div>

              <div className="report-detail-row">
                <span>Severity</span>
                <strong>
                  {report.detection?.severity || "—"}
                </strong>
              </div>

              <div className="report-detail-row">
                <span>Location</span>
                <strong>
                  {report.incident?.address ||
                    "Location not provided"}
                </strong>
              </div>

              <div className="report-detail-row">
                <span>Coordinates</span>
                <strong>
                  {report.incident?.latitude != null &&
                  report.incident?.longitude != null
                    ? `${report.incident.latitude}, ${report.incident.longitude}`
                    : "Not provided"}
                </strong>
              </div>

              <div className="report-detail-row">
                <span>Created</span>
                <strong>
                  {report.report.created_at
                    ? new Date(
                        report.report.created_at
                      ).toLocaleString()
                    : "—"}
                </strong>
              </div>

              {report.report.status === "Submitted" && (
                <>
                  <div className="report-authority-box">
                    <span>Municipal Authority</span>
                    <strong>
                      {report.report.authority_name}
                    </strong>
                  </div>

                  <div className="report-reference-box">
                    <span>Authority Reference</span>
                    <strong>
                      {report.report.authority_reference}
                    </strong>
                  </div>
                </>
              )}

              {report.report.status === "Draft" && (
                <button
                  className="submit-report-button"
                  onClick={handleSubmitReport}
                  disabled={submittingReport}
                >
                  {submittingReport
                    ? "Submitting Report..."
                    : "Submit to Municipal Authority"}
                </button>
              )}
            </div>
          </div>
        </div>
      )}
    </section>
  )
}

export default Results